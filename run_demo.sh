#!/usr/bin/env bash
#
# run_demo.sh — One-click launch for the BorrowBox containerized stack.
#
# Usage:
#   ./run_demo.sh          Start all services (build if needed)
#   ./run_demo.sh --build  Force a full rebuild of all images
#   ./run_demo.sh --stop   Stop and remove all containers
#   ./run_demo.sh --clean  Stop containers, remove volumes, and clear demo credentials (full reset)
#
set -euo pipefail

COMPOSE_FILE="docker-compose.yml"
PROJECT_DIR="$(cd "$(dirname "$0")" && pwd)"
CREDENTIALS_FILE="$PROJECT_DIR/.borrowbox-demo-credentials"

# Colors for terminal output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color

info()  { echo -e "${CYAN}[INFO]${NC}  $*"; }
ok()    { echo -e "${GREEN}[OK]${NC}    $*"; }
warn()  { echo -e "${YELLOW}[WARN]${NC}  $*"; }
err()   { echo -e "${RED}[ERROR]${NC} $*"; }

# ── JWT secret ───────────────────────────────────────────────

# Generate a temporary JWT secret for local demo runs when the operator has not
# supplied one. The value is never printed.
ensure_jwt_secret() {
    if [ -n "${APP_JWT_SECRET:-}" ]; then
        export APP_JWT_SECRET
        return 0
    fi

    if command -v openssl &>/dev/null; then
        APP_JWT_SECRET="$(openssl rand -base64 48 2>/dev/null | tr -d '\n')" || true
    fi

    if [ -z "${APP_JWT_SECRET:-}" ] && [ -r /dev/urandom ] && command -v base64 &>/dev/null; then
        APP_JWT_SECRET="$(head -c 48 /dev/urandom | base64 | tr -d '\n')" || true
    fi

    if [ -z "${APP_JWT_SECRET:-}" ]; then
        err "APP_JWT_SECRET is not set and no secure random generator is available."
        exit 1
    fi

    export APP_JWT_SECRET
    info "Generated a temporary APP_JWT_SECRET for this demo run."
}

# ── Local demo credentials ───────────────────────────────────

# Generate a URL-safe random password without relying on the database or shell
# history. The value is only ever written to the protected credentials file.
generate_demo_password() {
    local password=""

    if command -v openssl &>/dev/null; then
        password="$(openssl rand -base64 32 2>/dev/null | tr -d '\n=' | tr '+/' '-_')" || true
    fi

    if [ -z "$password" ] && [ -r /dev/urandom ] && command -v base64 &>/dev/null; then
        password="$(head -c 32 /dev/urandom | base64 | tr -d '\n=' | tr '+/' '-_')" || true
    fi

    if [ -z "$password" ]; then
        return 1
    fi

    printf '%s' "$password"
}

restrict_credentials_file() {
    if ! chmod 600 "$CREDENTIALS_FILE" 2>/dev/null; then
        err "Could not restrict permissions on $CREDENTIALS_FILE"
        err "Refusing to keep a demo password readable by other users."
        return 1
    fi
}

detect_demo_database() {
    COMPOSE_PROJECT="$($COMPOSE_CMD -f "$COMPOSE_FILE" config 2>/dev/null \
        | awk '/^name:/{print $2; exit}' || true)"
    COMPOSE_PROJECT="${COMPOSE_PROJECT:-borrowbox}"

    DB_PRESENT=0
    if $COMPOSE_CMD -f "$COMPOSE_FILE" ps -a -q mysql 2>/dev/null | grep -q .; then
        DB_PRESENT=1
    fi
    if docker volume ls \
        --filter "label=com.docker.compose.project=$COMPOSE_PROJECT" \
        --filter "label=com.docker.compose.volume=mysql_data" \
        --format '{{.Name}}' 2>/dev/null | grep -q .; then
        DB_PRESENT=1
    fi
}

write_credentials_file() {
    local temp_file
    temp_file="$(mktemp "${CREDENTIALS_FILE}.XXXXXX")" || {
        err "Could not create a temporary local credential file."
        return 1
    }

    (
        umask 077
        {
            echo "# BorrowBox local demo credentials."
            echo "# Generated by run_demo; this file is ignored by Git."
            echo "BORROWBOX_SEED_PASSWORD=$SEED_PASSWORD"
            echo "MYSQL_ROOT_PASSWORD=$MYSQL_PASSWORD"
            echo "BORROWBOX_APP_DB_PASSWORD=$APP_DB_PASSWORD"
            echo "BORROWBOX_E2E_DB_PASSWORD=$E2E_DB_PASSWORD"
            echo ""
            echo "Demo users:"
            echo "  ahmed@example.com"
            echo "  salah@example.com"
            echo "  omar@example.com"
            echo "  youssef@example.com"
            echo "  karim@example.com"
        } > "$temp_file"
    ) || {
        rm -f "$temp_file"
        err "Could not write the local demo credential file: $CREDENTIALS_FILE"
        return 1
    }

    if ! chmod 600 "$temp_file" 2>/dev/null; then
        rm -f "$temp_file"
        err "Could not restrict permissions on $CREDENTIALS_FILE"
        err "Refusing to keep a demo password readable by other users."
        return 1
    fi

    if ! mv -f "$temp_file" "$CREDENTIALS_FILE"; then
        rm -f "$temp_file"
        err "Could not replace the local demo credential file: $CREDENTIALS_FILE"
        return 1
    fi
}

# Compose requires values for interpolation even for commands that do not connect
# to the database (for example `down`). Fill any missing value with a temporary
# random one; start reuses or writes the real credentials file later.
ensure_compose_interpolation_defaults() {
    if [ -z "${MYSQL_ROOT_PASSWORD:-}" ]; then
        MYSQL_ROOT_PASSWORD="$(generate_demo_password)" || {
            err "Could not generate a temporary MySQL credential for Compose."
            return 1
        }
        export MYSQL_ROOT_PASSWORD
    fi

    if [ -z "${BORROWBOX_APP_DB_PASSWORD:-}" ]; then
        BORROWBOX_APP_DB_PASSWORD="$(generate_demo_password)" || {
            err "Could not generate a temporary app database credential for Compose."
            return 1
        }
        export BORROWBOX_APP_DB_PASSWORD
    fi

    if [ -z "${BORROWBOX_E2E_DB_PASSWORD:-}" ]; then
        BORROWBOX_E2E_DB_PASSWORD="$(generate_demo_password)" || {
            err "Could not generate a temporary E2E database credential for Compose."
            return 1
        }
        export BORROWBOX_E2E_DB_PASSWORD
    fi
}

ensure_seed_credentials() {
    cd "$PROJECT_DIR"
    SEED_PASSWORD=""
    MYSQL_PASSWORD=""
    APP_DB_PASSWORD=""
    E2E_DB_PASSWORD=""
    local need_write=0

    if ! ensure_compose_interpolation_defaults; then
        exit 1
    fi

    if [ -f "$CREDENTIALS_FILE" ]; then
        if [ ! -r "$CREDENTIALS_FILE" ]; then
            err "The local demo credential file is unreadable: $CREDENTIALS_FILE"
            err "Restore it, or run ./run_demo.sh --clean to remove the demo database and start fresh."
            exit 1
        fi

        SEED_PASSWORD="$(sed -n 's/^BORROWBOX_SEED_PASSWORD=//p' "$CREDENTIALS_FILE" | head -n 1 | tr -d '\r')"
        MYSQL_PASSWORD="$(sed -n 's/^MYSQL_ROOT_PASSWORD=//p' "$CREDENTIALS_FILE" | head -n 1 | tr -d '\r')"
        APP_DB_PASSWORD="$(sed -n 's/^BORROWBOX_APP_DB_PASSWORD=//p' "$CREDENTIALS_FILE" | head -n 1 | tr -d '\r')"
        E2E_DB_PASSWORD="$(sed -n 's/^BORROWBOX_E2E_DB_PASSWORD=//p' "$CREDENTIALS_FILE" | head -n 1 | tr -d '\r')"
        if [ -z "$SEED_PASSWORD" ]; then
            err "The local demo credential file does not contain BORROWBOX_SEED_PASSWORD: $CREDENTIALS_FILE"
            err "Restore it, or run ./run_demo.sh --clean to remove the demo database and start fresh."
            exit 1
        fi

        if [ -z "$MYSQL_PASSWORD" ]; then
            detect_demo_database
            if [ "$DB_PRESENT" = "1" ]; then
                err "The local demo credential file does not contain MYSQL_ROOT_PASSWORD:"
                err "  $CREDENTIALS_FILE"
                err "An existing demo database keeps the root password it was created with;"
                err "changing the credential file alone does not rotate the database password."
                err "If this database predates the credential-file change, set MYSQL_ROOT_PASSWORD"
                err "to the root password that database already uses."
                err "Otherwise, run ./run_demo.sh --clean (destructive) to start fresh."
                exit 1
            fi

            if ! MYSQL_PASSWORD="$(generate_demo_password)"; then
                err "Could not generate a local MySQL root password."
                exit 1
            fi
            need_write=1
        fi

        if [ -z "$APP_DB_PASSWORD" ]; then
            if ! APP_DB_PASSWORD="$(generate_demo_password)"; then
                err "Could not generate a local app database password."
                exit 1
            fi
            need_write=1
        fi

        if [ -z "$E2E_DB_PASSWORD" ]; then
            if ! E2E_DB_PASSWORD="$(generate_demo_password)"; then
                err "Could not generate a local E2E database password."
                exit 1
            fi
            need_write=1
        fi

        if [ "$need_write" = "1" ]; then
            if ! write_credentials_file; then
                exit 1
            fi
            ok "Updated $CREDENTIALS_FILE with the missing database credentials."
        fi

        if ! restrict_credentials_file; then
            exit 1
        fi
        ok "Using existing local demo credentials file."
    else
        detect_demo_database
        if [ "$DB_PRESENT" = "1" ]; then
            err "A BorrowBox demo database exists, but the local credential file is missing:"
            err "  $CREDENTIALS_FILE"
            err "The file must contain BORROWBOX_SEED_PASSWORD, MYSQL_ROOT_PASSWORD,"
            err "BORROWBOX_APP_DB_PASSWORD, and BORROWBOX_E2E_DB_PASSWORD."
            err "Restore the credential file, or run ./run_demo.sh --clean."
            err "--clean deletes the demo database and all of its data."
            exit 1
        fi

        if ! SEED_PASSWORD="$(generate_demo_password)"; then
            err "Could not generate a local demo password."
            exit 1
        fi
        if ! MYSQL_PASSWORD="$(generate_demo_password)"; then
            err "Could not generate a local MySQL root password."
            exit 1
        fi
        if ! APP_DB_PASSWORD="$(generate_demo_password)"; then
            err "Could not generate a local app database password."
            exit 1
        fi
        if ! E2E_DB_PASSWORD="$(generate_demo_password)"; then
            err "Could not generate a local E2E database password."
            exit 1
        fi
        if ! write_credentials_file; then
            exit 1
        fi

        ok "Generated local demo credentials in $CREDENTIALS_FILE"
        info "Open that file to retrieve the demo account and MySQL passwords."
    fi

    export BORROWBOX_SEED_ENABLED=true
    export BORROWBOX_SEED_PASSWORD="$SEED_PASSWORD"
    export MYSQL_ROOT_PASSWORD="$MYSQL_PASSWORD"
    export BORROWBOX_APP_DB_PASSWORD="$APP_DB_PASSWORD"
    export BORROWBOX_E2E_DB_PASSWORD="$E2E_DB_PASSWORD"
}

# ── Pre-flight checks ────────────────────────────────────────

check_docker() {
    if ! command -v docker &>/dev/null; then
        err "Docker is not installed or not in PATH."
        echo "  Install Docker Desktop: https://docs.docker.com/get-docker/"
        exit 1
    fi

    if ! docker info &>/dev/null; then
        err "Docker daemon is not running. Please start Docker Desktop and retry."
        exit 1
    fi
    ok "Docker is available and running."
}

check_compose() {
    if docker compose version &>/dev/null; then
        ok "Docker Compose (plugin) detected."
        COMPOSE_CMD="docker compose"
    elif command -v docker-compose &>/dev/null; then
        ok "docker-compose (standalone) detected."
        COMPOSE_CMD="docker-compose"
    else
        err "Docker Compose is not installed."
        echo "  Install it via Docker Desktop or: https://docs.docker.com/compose/install/"
        exit 1
    fi
}

# ── Actions ───────────────────────────────────────────────────

do_stop() {
    info "Stopping BorrowBox containers..."
    cd "$PROJECT_DIR"
    ensure_compose_interpolation_defaults
    $COMPOSE_CMD -f "$COMPOSE_FILE" down
    ok "Containers stopped."
}

do_clean() {
    info "Stopping BorrowBox containers and removing volumes..."
    cd "$PROJECT_DIR"
    ensure_compose_interpolation_defaults
    $COMPOSE_CMD -f "$COMPOSE_FILE" down -v
    rm -f "$CREDENTIALS_FILE"
    ok "Containers stopped, volumes removed, and local demo credentials cleared."
}

do_start() {
    local build_flag="${1:-}"

    info "Starting BorrowBox..."
    echo ""
    echo "  Stack:"
    echo "    MySQL 8.0       → localhost:3307  (container-internal: 3306)"
    echo "    Backend API     → localhost:8080"
    echo "    Frontend (Nginx)→ localhost:3000"
    echo ""

    cd "$PROJECT_DIR"
    ensure_seed_credentials

    if [ "$build_flag" = "--build" ]; then
        info "Building images from source (this may take a few minutes)..."
        $COMPOSE_CMD -f "$COMPOSE_FILE" up --build -d
    else
        $COMPOSE_CMD -f "$COMPOSE_FILE" up -d
    fi

    echo ""
    info "Waiting for services to become healthy..."

    # Wait up to 120 seconds for the backend to respond
    local max_wait=120
    local elapsed=0
    local interval=5

    while [ $elapsed -lt $max_wait ]; do
        if curl -sf http://localhost:8080/api/health > /dev/null 2>&1; then
            ok "Backend API is healthy."
            break
        fi
        sleep $interval
        elapsed=$((elapsed + interval))
        info "  Waiting for backend... (${elapsed}s / ${max_wait}s)"
    done

    if [ $elapsed -ge $max_wait ]; then
        warn "Backend did not respond within ${max_wait}s."
        warn "Check logs with: $COMPOSE_CMD -f $COMPOSE_FILE logs backend"
    fi

    echo ""
    echo "────────────────────────────────────────────"
    ok "BorrowBox is running!"
    echo ""
    echo "  Frontend:   http://localhost:3000"
    echo "  Backend API: http://localhost:8080"
    echo "  Health:      http://localhost:8080/api/health"
    echo "  Credentials: $CREDENTIALS_FILE"
    echo ""
    echo "  Stop:        ./run_demo.sh --stop"
    echo "  Full reset:  ./run_demo.sh --clean"
    echo "  View logs:   $COMPOSE_CMD -f $COMPOSE_FILE logs -f"
    echo "────────────────────────────────────────────"
}

# ── Main ──────────────────────────────────────────────────────

main() {
    echo ""
    echo "╔══════════════════════════════════════╗"
    echo "║       BorrowBox Demo Launcher        ║"
    echo "╚══════════════════════════════════════╝"
    echo ""

    check_docker
    check_compose
    ensure_jwt_secret
    ensure_compose_interpolation_defaults

    case "${1:-}" in
        --stop)
            do_stop
            ;;
        --clean)
            do_clean
            ;;
        --build)
            do_start "--build"
            ;;
        "")
            do_start ""
            ;;
        *)
            echo "Usage: $0 [--build|--stop|--clean]"
            exit 1
            ;;
    esac
}

main "$@"
